export function t(lang, key, params = {}) {
  const dict = STRINGS[lang] || STRINGS.pt;
  let cur = dict;
  for (const part of key.split('.')) {
    cur = cur?.[part];
  }
  const tpl = typeof cur === 'string' ? cur : key;
  return tpl.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}
